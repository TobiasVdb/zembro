import type { FieldType, Lang } from '../shared/types.js'
import type { SeedField } from './content.js'

const text = (path: string, nl: string, en: string, fr: string, de: string): SeedField => ({
  path,
  type: 'text',
  values: { nl, en, fr, de },
})
const shared = (path: string, value: string, type: FieldType = 'text'): SeedField => ({
  path,
  type,
  values: Object.fromEntries(['nl', 'en', 'fr', 'de'].map((lang) => [lang, value])) as Record<
    Lang,
    string
  >,
})
const product = (name: string, image: string, shopLink: string, fields: SeedField[]) => [
  shared('name', name),
  shared('image', image, 'image'),
  shared('shopLink', shopLink, 'link'),
  text(
    'imageAlt',
    `${name} van Zembro`,
    `${name} by Zembro`,
    `${name} de Zembro`,
    `${name} von Zembro`,
  ),
  ...fields,
]

